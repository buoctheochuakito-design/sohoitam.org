export function getDailyPrayerFocus(dateKey: string, feastTitle: string, season: string): string {
  const [, monthStr, dayStr] = dateKey.split('-');
  const day = Number(dayStr);
  const month = Number(monthStr);

  const dailyIntentions = [
    'Cầu cho hòa bình thế giới và các dân tộc đang chịu chiến tranh, chia rẽ.',
    'Cầu cho các linh hồn nơi Luyện ngục, các bậc tổ tiên, ông bà cha mẹ đã qua đời.',
    'Cầu cho ơn gọi linh mục, tu sĩ và lòng nhiệt thành truyền giáo tại Việt Nam.',
    'Cầu cho các gia đình Công giáo luôn trung thành yêu thương và giữ vững đức tin.',
    'Cầu cho người bệnh tật, người cao tuổi neo đơn và các y bác sĩ đang phục vụ.',
    'Cầu cho giới trẻ biết phân định ơn gọi và can đảm sống chứng nhân Tin Mừng.',
    'Cầu cho những người nghèo khổ, lao động xa quê và các em nhỏ thiếu cơ hội học tập.',
  ];

  const baseIntention = dailyIntentions[(day + month) % dailyIntentions.length];
  return `Hiệp ý trong ngày (${feastTitle} · ${season}): ${baseIntention}`;
}
